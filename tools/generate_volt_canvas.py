"""Compile only our authored Volt RML into immutable native Canvas geometry.

This reads source owned by this project; it neither exports nor signs Rive
files and does not involve a Rive account. The remaining 31 rigs are untouched.
"""

import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
PROPERTIES = {"13": "x", "14": "y", "15": "rotation", "16": "scaleX",
              "17": "scaleY", "18": "opacity", "38": "colorValue"}


def number(element, key, default=0):
    return float(element.get(key, default))


def dart(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (int, float)):
        return str(int(value)) if int(value) == value else repr(value)
    if isinstance(value, list):
        return "[" + ",".join(dart(item) for item in value) + "]"
    raise TypeError(value)


HEADER = """// Generated by tools/generate_volt_canvas.py from our authored Volt RML.
// Immutable geometry; paths and paints are compiled once by volt_model.dart.
// Do not hand edit: only Volt is selected; no Rive binary is modified.

class VoltGeometryNode {
  const VoltGeometryNode(this.name, {this.x=0, this.y=0, this.rotation=0,
    this.scaleX=1, this.scaleY=1, this.opacity=1, this.xBinding='',
    this.yBinding='', this.rotationBinding='', this.scaleXBinding='',
    this.scaleYBinding='', this.opacityBinding='', this.children=const [],
    this.path=-1, this.paints=const []});
  final String name, xBinding, yBinding, rotationBinding, scaleXBinding,
    scaleYBinding, opacityBinding;
  final double x, y, rotation, scaleX, scaleY, opacity;
  final List<int> children, paints;
  final int path;
}
class VoltGeometryPath {
  const VoltGeometryPath(this.kind, this.data, {this.closed=true});
  // 0 ellipse, 1 rounded rectangle, 2 rounded straight-vertex polygon.
  final int kind;
  final List<double> data;
  final bool closed;
}
class VoltGeometryPaint {
  const VoltGeometryPaint(this.kind, this.colors, {this.stops=const [],
    this.accentStops=const [], this.startX=0, this.startY=0, this.endX=0,
    this.endY=0, this.stroke=0, this.cap='butt', this.join='miter'});
  // 0 solid, 1 linear gradient, 2 radial gradient.
  final int kind;
  final List<int> colors, accentStops;
  final List<double> stops;
  final double startX, startY, endX, endY, stroke;
  final String cap, join;
}
"""


def compile_geometry(source):
    root = ET.parse(source).getroot()
    boards = [node for node in root.findall("Artboard") if node.get("name") == "volt"]
    assert len(boards) == 1, "Exactly one authored Volt artboard is required"
    board = boards[0]
    vm = next(node for node in root.findall("ViewModel") if node.get("id") == board.get("viewModelId"))
    fields = {node.get("id"): node.get("name") for node in vm if node.tag.startswith("ViewModelProperty")}
    instance = vm.find("ViewModelInstance")
    defaults = {fields[node.get("viewModelPropertyId")]: float(node.get("propertyValue"))
                for node in instance if node.tag == "ViewModelInstanceNumber"}

    def bindings(node):
        result = {}
        for bind in node.findall("DataBindContext"):
            key = PROPERTIES[bind.get("propertyKey")]
            field_id = bind.get("sourcePathIds").split("-")[-1]
            result[key] = fields[field_id]
        return result

    paths, paints, nodes = [], [], []
    path_ids, paint_ids = {}, {}

    def intern(value, collection, indexes):
        key = json.dumps(value, sort_keys=True)
        if key not in indexes:
            indexes[key] = len(collection)
            collection.append(value)
        return indexes[key]

    def path_data(shape):
        geometry = [child for child in shape if child.tag in {"Ellipse", "Rectangle", "PointsPath"}]
        assert len(geometry) == 1, shape.get("name")
        geometry = geometry[0]
        if geometry.tag in {"Ellipse", "Rectangle"}:
            data = [number(geometry, "width"), number(geometry, "height"),
                    number(geometry, "originX", .5), number(geometry, "originY", .5)]
            if geometry.tag == "Rectangle":
                tl = number(geometry, "cornerRadiusTL")
                linked = geometry.get("linkCornerRadius", "true") == "true"
                data += [tl, tl if linked else number(geometry, "cornerRadiusTR"),
                         tl if linked else number(geometry, "cornerRadiusBR"),
                         tl if linked else number(geometry, "cornerRadiusBL")]
            return {"kind": 0 if geometry.tag == "Ellipse" else 1, "data": data}
        assert all(vertex.tag == "StraightVertex" for vertex in geometry), shape.get("name")
        return {"kind": 2, "data": [number(vertex, key) for vertex in geometry
                  for key in ("x", "y", "radius")],
                "closed": geometry.get("isClosed", "false") == "true"}

    def paint_data(paint):
        entries = [child for child in paint if child.tag != "DataBindContext"]
        assert len(entries) == 1, paint.tag
        entry = entries[0]
        assert entry.tag in {"SolidColor", "LinearGradient", "RadialGradient"}, entry.tag
        data = {"kind": {"SolidColor": 0, "LinearGradient": 1, "RadialGradient": 2}[entry.tag]}
        if entry.tag == "SolidColor":
            data["colors"] = [int(entry.get("colorValue"), 16)]
            if bindings(entry).get("colorValue") == "accent":
                data["accentStops"] = [0]
        else:
            stops = list(entry.findall("GradientStop"))
            data["colors"] = [int(stop.get("colorValue"), 16) for stop in stops]
            data["stops"] = [number(stop, "position") for stop in stops]
            accent = [i for i, stop in enumerate(stops) if bindings(stop).get("colorValue") == "accent"]
            if accent:
                data["accentStops"] = accent
            data.update({key: number(entry, key) for key in ("startX", "startY", "endX", "endY")})
        if paint.tag == "Stroke":
            data.update(stroke=number(paint, "thickness"), cap=paint.get("cap", "butt"), join=paint.get("join", "miter"))
        return data

    def node_data(node):
        index = len(nodes)
        data = {"name": node.get("name", ""), "children": []}
        nodes.append(data)
        for key, default in [("x", 0), ("y", 0), ("rotation", 0),
                             ("scaleX", 1), ("scaleY", 1), ("opacity", 1)]:
            value = number(node, key, default)
            if value != default:
                data[key] = value
        for key, field in bindings(node).items():
            assert key != "colorValue"
            data[key + "Binding"] = field
        if node.tag == "Shape":
            data["path"] = intern(path_data(node), paths, path_ids)
            # Rive stores front first; Canvas draws the back first.
            data["paints"] = [intern(paint_data(paint), paints, paint_ids)
                              for paint in reversed(list(node)) if paint.tag in {"Fill", "Stroke"}]
        for child in reversed(list(node)):
            if child.tag in {"Node", "Shape"}:
                data["children"].append(node_data(child))
        return index

    robot = next(node for node in board.findall("Node") if node.get("name") == "Robot")
    node_data(robot)
    result = [HEADER]
    digest = hashlib.sha256(ET.tostring(board) + ET.tostring(vm)).hexdigest()
    result.append(f"const voltGeometrySourceSha256 = '{digest}';\n")
    result.append(f"const voltGeometryShapeCount = {len(list(robot.iter('Shape')))};\n")
    result.append("const voltGeometryDefaults = <String,double>{" +
                  ",".join(f"{dart(k)}:{dart(v)}" for k, v in defaults.items()) + "};\n")
    result.append("const voltGeometryPaths = <VoltGeometryPath>[\n")
    for path in paths:
        suffix = f",closed:{dart(path['closed'])}" if "closed" in path else ""
        result.append(f"  VoltGeometryPath({path['kind']},{dart(path['data'])}{suffix}),\n")
    result.append("];\nconst voltGeometryPaints = <VoltGeometryPaint>[\n")
    for paint in paints:
        colors = "[" + ",".join(f"0x{value:08X}" for value in paint["colors"]) + "]"
        suffix = ",".join(f"{key}:{dart(value)}" for key, value in paint.items() if key not in {"kind", "colors"})
        result.append(f"  VoltGeometryPaint({paint['kind']},{colors}{',' if suffix else ''}{suffix}),\n")
    result.append("];\nconst voltGeometryNodes = <VoltGeometryNode>[\n")
    for node in nodes:
        suffix = ",".join(f"{key}:{dart(value)}" for key, value in node.items() if key != "name" and value != [])
        result.append(f"  VoltGeometryNode({dart(node['name'])}{',' if suffix else ''}{suffix}),\n")
    result.append("];\n")
    return "".join(result), {"source": str(source), "artboard": "volt", "shapes": len(list(robot.iter("Shape"))),
                             "nodes": len(nodes), "unique_paths": len(paths), "unique_paints": len(paints), "sha256": digest}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "animation/rive/game_robot/scene.rml")
    parser.add_argument("--out", type=Path, default=ROOT / "extensions/flet_rive/lib/src/robot/volt_geometry.dart")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text, summary = compile_geometry(args.source)
    if args.check:
        # Dart format is deliberately optional for generated geometry. The
        # stable compiler output is byte-checkable without requiring an SDK.
        assert args.out.read_text(encoding="utf-8") == text, "Regenerate Volt geometry after authoring RML"
    else:
        args.out.write_text(text, encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False))


if __name__ == "__main__":
    main()
