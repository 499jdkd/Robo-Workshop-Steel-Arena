({VoltBeat a, VoltBeat b, double w}) _span(
  List<VoltBeat> keys,
  double t,
  double lag,
) {
  final time = unit((t - lag) / (1 - lag));
  for (var i = 1; i < keys.length; i++) {
    if (time <= keys[i].t)
      return (
        a: keys[i - 1],
        b: keys[i],
        w: smooth((time - keys[i - 1].t) / (keys[i].t - keys[i - 1].t)),
      );
  }
  return (a: keys.last, b: keys.last, w: 0);
}

