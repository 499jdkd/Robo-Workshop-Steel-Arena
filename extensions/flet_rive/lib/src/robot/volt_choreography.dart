  final keys = voltBeats[action], f = p.extra;
  for (final entry in voltMechanismDefaults.entries) f[entry.key] = entry.value;
  if (keys != null) {
    final root = _span(keys, t, 0),
        head = _span(keys, t, .025),
        left = _span(keys, t, .012),
        right = _span(keys, t, .022),
        elbowL = _span(keys, t, .033),
        elbowR = _span(keys, t, .046),
        coilL = _span(keys, t, .026),
        coilR = _span(keys, t, .043);
    double lerp(double a, double b, double w) => a + (b - a) * w;
    p.x = baseX + lerp(root.a.x, root.b.x, root.w);
    p.y = baseY + lerp(root.a.y, root.b.y, root.w);
    p.rotation = lerp(root.a.roll, root.b.roll, root.w);
    p.body = lerp(root.a.body, root.b.body, root.w);
    p.bodyY = baseBodyY + lerp(root.a.bodyY, root.b.bodyY, root.w);
    p.head = lerp(head.a.head, head.b.head, head.w);
    p.headY = baseHeadY + lerp(head.a.headY, head.b.headY, head.w);
    p.armL = lerp(left.a.left, left.b.left, left.w);
    p.armR = lerp(right.a.right, right.b.right, right.w);
    p.foreL = lerp(elbowL.a.elbowL, elbowL.b.elbowL, elbowL.w);
    p.foreR = lerp(elbowR.a.elbowR, elbowR.b.elbowR, elbowR.w);
    f['joint0'] = lerp(coilL.a.mastL, coilL.b.mastL, coilL.w);
    f['joint1'] = lerp(coilR.a.mastR, coilR.b.mastR, coilR.w);
    f['joint8'] = lerp(left.a.hipL, left.b.hipL, left.w);
    f['joint9'] = lerp(right.a.hipR, right.b.hipR, right.w);
    f['joint14'] = lerp(elbowL.a.ankleL, elbowL.b.ankleL, elbowL.w);
    f['joint15'] = lerp(elbowR.a.ankleR, elbowR.b.ankleR, elbowR.w);
    f['voltLegLX'] = lerp(left.a.stepL, left.b.stepL, left.w);
    f['voltLegRX'] = lerp(right.a.stepR, right.b.stepR, right.w);
    f['voltLegLY'] = lerp(left.a.legL, left.b.legL, left.w);
    f['voltLegRY'] = lerp(right.a.legR, right.b.legR, right.w);
    final compression = lerp(root.a.compress, root.b.compress, root.w);
    f['bodyscaleY'] = 1 - .025 * compression;
    f['bodyscaleX'] = 1 + .016 * compression;
  } else {
    f['joint8'] = .025 * math.sin(t * math.pi * 2);
    f['joint9'] = -f['joint8']!;
  }
  // Linked but separate actuators: rods telescope, shoulder rings counterturn,
  // and the optical screen lags behind the heavier helmet.
  f['voltShoulderL'] = -p.armL * .12 + p.foreL * .06;
  f['voltShoulderR'] = -p.armR * .12 + p.foreR * .06;
  f['voltPistonL'] = 19 + 5 * math.sin(p.foreL);
  f['voltPistonR'] = 19 - 5 * math.sin(p.foreR);
  f['voltStrutL'] = ((f['voltLegLY']! - 56) / 22).clamp(.35, 1.5);
  f['voltStrutR'] = ((f['voltLegRY']! - 56) / 22).clamp(.35, 1.5);
  f['voltOpticY'] = -9 - p.head * 3;
  f['voltOpticRoll'] = -p.head * .12;
}
